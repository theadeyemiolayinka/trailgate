// Generates packages/core/src/schemas.embedded.ts from spec/schemas/*.schema.json.
// The generated module lets single-file bundles (scripts/bundle.mjs) validate
// documents without a spec/schemas directory on disk. Run: pnpm embed.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dir = join(root, 'spec', 'schemas');
const entries = [];
for (const file of readdirSync(dir).sort()) {
  if (!file.endsWith('.schema.json')) {
    continue;
  }
  const schema = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  if (typeof schema.$id !== 'string') {
    throw new Error(`schema ${file} has no $id`);
  }
  entries.push([schema.$id, schema]);
}

const body = `// Generated by scripts/embed-schemas.mjs from spec/schemas/*.schema.json.
// Do not edit by hand; run \`pnpm embed\` after changing a schema.
export const EMBEDDED_SCHEMAS: Record<string, Record<string, unknown>> = JSON.parse(
  ${JSON.stringify(JSON.stringify(Object.fromEntries(entries)))},
) as Record<string, Record<string, unknown>>;
`;
writeFileSync(join(root, 'packages/core/src/schemas.embedded.ts'), body);
console.log(`wrote packages/core/src/schemas.embedded.ts (${entries.length} schemas)`);
